std::atomic<uint64_t> gInstanceCounter{1};

/// The namespace OPC 10000-19 fixes for a direct dictionary-entry instance, and the clause that fixes it.
struct DictionaryNamespace
{
  string_view uri;
  string_view clause;
};

VoidResult validate_variable_instantiation_shape(
  const NodeId& typeDefinition, const VariableInstantiationAttributes& attributes)
{
  if (typeDefinition != NodeId{VariableTypeId::YArrayItemType})
  {
    return {};
  }

  // Part 8 section 5.3.4.2 narrows YArrayItemType's prose-level BaseDataType declaration to these
  // eight concrete numeric DataTypes. The NS0 type node cannot encode that restriction, so it must
  // be enforced before the generic instantiation flow publishes a root.
  constexpr std::array<DataTypeId, 8> permittedDataTypes{DataTypeId::SByte,
    DataTypeId::Int16,
    DataTypeId::Int32,
    DataTypeId::Int64,
    DataTypeId::Float,
    DataTypeId::Double,
    DataTypeId::ComplexNumberType,
    DataTypeId::DoubleComplexNumberType};

  if (!attributes.dataType)
  {
    return VoidResult{Status::BadTypeMismatch,
      ErrorDetail::build("YArrayItemDataTypeRequired",
        "YArrayItemType requires an explicit permitted numeric DataType",
        "InstantiationService")
        .context(ContextKeys::expected,
          "SByte, Int16, Int32, Int64, Float, Double, ComplexNumberType, or DoubleComplexNumberType")};
  }

  const bool dataTypePermitted = std::ranges::any_of(permittedDataTypes,
    [&attributes](DataTypeId permitted) { return *attributes.dataType == NodeId{permitted}; });
  if (!dataTypePermitted)
  {
    return VoidResult{Status::BadTypeMismatch,
      ErrorDetail::build("YArrayItemDataTypeInvalid",
        "YArrayItemType DataType is outside the permitted numeric set",
        "InstantiationService")
        .context(ContextKeys::actual, ua::to_string(*attributes.dataType))
        .context(ContextKeys::expected,
          "SByte, Int16, Int32, Int64, Float, Double, ComplexNumberType, or DoubleComplexNumberType")};
  }

  if (attributes.valueRank && *attributes.valueRank != 1)
  {
    return VoidResult{Status::BadTypeMismatch,
      ErrorDetail::build(
        "YArrayItemValueRankInvalid", "YArrayItemType requires ValueRank 1", "InstantiationService")
        .context(ContextKeys::actual, std::to_string(*attributes.valueRank))
        .context(ContextKeys::expected, "1")};
  }

  return {};
}

/// The index of the namespace with @p uri, or nothing when none is registered.
optional<uint16_t> registered_namespace_index(AddressSpace& addressSpace, string_view uri)
{
  try
  {
    return addressSpace.namespace_array().get_namespace_index(uri);
  }
  catch (const UaException& exception)
  {
    if (exception.status() != Status::BadOutOfRange)
    {
      throw;
    }
    return std::nullopt;
  }
}

optional<DictionaryNamespace> direct_dictionary_namespace(const NodeId& typeDefinition) noexcept
{
  if (typeDefinition == NodeId{ObjectTypeId::IrdiDictionaryEntryType})
  {
    return DictionaryNamespace{irdiDictionaryNamespaceUri, "OPC 10000-19 5.3"};
  }
  if (typeDefinition == NodeId{ObjectTypeId::UriDictionaryEntryType})
  {
    return DictionaryNamespace{uriDictionaryNamespaceUri, "OPC 10000-19 5.4"};
  }
  return std::nullopt;
}

NodeId allocate_string_node_id(uint16_t nsIndex)
{
  const auto id = gInstanceCounter.fetch_add(1, std::memory_order_relaxed);
  return NodeId{nsIndex, fmt::format("inst:{}", id)};
}

NodeId allocate_node_id(const NodeIdAllocator& allocator, uint16_t nsIndex, const QualifiedName& browseName)
{
  if (allocator)
  {
    return allocator(nsIndex, browseName);
  }
  // Fallback ignores browseName - produces a unique string id.
  return allocate_string_node_id(nsIndex);
}

/// Resolve the NamespaceIndex used for allocating a server-generated instance NodeId.
///
/// Part 5 4.1 forbids server-generated nodes from using NamespaceIndex 0 - they
/// are "not defined by the OPC Foundation but generated by the Server". The rule:
///
///   1. Explicit `targetOverride` always wins (caller is explicit about where the
///      subtree should live; sourced from `InstantiationOptions::targetNamespaceIndex`).
///   2. Otherwise the parent's NSI is used (typical case: instance lives where its
///      parent lives).
///   3. If the parent is NSI 0, fall back to NSI 1 - Part 5 6.3.x reserves NSI 1
///      for the local Server's URI.
uint16_t resolve_target_namespace_index(
  const std::optional<uint16_t>& targetOverride, uint16_t parentNsIndex) noexcept
{
  if (targetOverride.has_value())
  {
    return *targetOverride;
  }
  if (parentNsIndex != 0)
  {
    return parentNsIndex;
  }
  return 1;
}

/// Seed a create-with-attributes set with the node's own BrowseName and the DisplayName derived
/// from it - the two attributes every instantiated node sets verbatim, in the same wire form the
/// NodeAccessor setters use (`Variant{QualifiedName}` / `Variant{LocalizedText}`).
ua::InitialAttributes make_browse_display_attributes(const QualifiedName& browseName)
{
  ua::InitialAttributes attributes;
  attributes.emplace_back(AttributeId::BrowseName, attribute_wire::browse_name(browseName));
  attributes.emplace_back(
    AttributeId::DisplayName, attribute_wire::display_name(LocalizedText{browseName.name()}));
  return attributes;
}

using OptionalNodeIdResult = Result<optional<NodeId>>;

/// What a step answers when the address space its operation holds weakly has been released
/// (COMP-SVR-NAMESPACE-CALLS-21 rules 1 and 2).
StatusCode instantiation_address_space_gone()
{
  return ::ua::detail::address_space_gone("InstantiationService");
}

/// Looks up @p nodeId through @p addressSpace, or answers that it has been released.
void find_node_weak(const WeakAddressSpace& addressSpace, const NodeId& nodeId,
  std::function<void(NodeAccessorResult)> completion)
{
  auto locked = addressSpace.lock();
  if (!locked)
  {
    completion(NodeAccessorResult{instantiation_address_space_gone()});
    return;
  }
  locked->find_node_async(nodeId, std::move(completion));
}

/// Find the modelling rule NodeId for a declaration node - async form.
/// Single-step (one get_references), so the iteration runs synchronously
/// inside the get_references continuation. No heap struct needed.
void get_modelling_rule_async(
  NodeAccessor declaration, std::function<void(OptionalNodeIdResult)> onComplete) noexcept
{
  declaration.get_references_async(
    [onComplete = std::move(onComplete)](NodeAccessor::ReferencesResult result) mutable
    {
      if (!result.is_good())
      {
        onComplete(OptionalNodeIdResult{
          ::ua::detail::references_failure(result.status_code(), "InstantiationService")});
        return;
      }
      for (const auto& ref : result.value())
      {
        if (!ref.is_forward() || ref.is_remote())
        {
          continue;
        }
        if (ref.type_id() != NodeId{ReferenceTypeId::HasModellingRule})
        {
          continue;
        }
        const auto& target = ref.target_id();
        if (target.is_local())
        {
          onComplete(OptionalNodeIdResult{optional<NodeId>{target.node_id()}});
          return;
        }
      }
      onComplete(OptionalNodeIdResult{optional<NodeId>{}});
    });
}

void get_type_definition_id_async(
  NodeAccessor node, std::function<void(OptionalNodeIdResult)> onComplete) noexcept
{
  node.get_references_async(
    [onComplete = std::move(onComplete)](NodeAccessor::ReferencesResult result) mutable
    {
      if (!result.is_good())
      {
        onComplete(OptionalNodeIdResult{
          ::ua::detail::references_failure(result.status_code(), "InstantiationService")});
        return;
      }
      for (const auto& ref : result.value())
      {
        if (!ref.is_forward() || ref.is_remote())
        {
          continue;
        }
        if (ref.type_id() != NodeId{ReferenceTypeId::HasTypeDefinition})
        {
          continue;
        }
        const auto& target = ref.target_id();
        if (target.is_local())
        {
          onComplete(OptionalNodeIdResult{optional<NodeId>{target.node_id()}});
          return;
        }
      }
      onComplete(OptionalNodeIdResult{optional<NodeId>{}});
    });
}

/// Whether @p type is an ObjectType or VariableType whose IsAbstract is set. An unset IsAbstract is false,
/// the attribute's default.
bool is_abstract_type(const NodeAccessor& type)
{
  const NodeClass nodeClass = type.get_node_class();
  if (nodeClass != NodeClass::ObjectType && nodeClass != NodeClass::VariableType)
  {
    return false;
  }
  const Variant isAbstract = type.read_attribute(AttributeId::IsAbstract);
  return isAbstract.is_boolean() && isAbstract.as<bool>();
}

/// OPC 10000-3 section 5.5.2: an abstract type has no instances of its own, only instances of its subtypes.
StatusCode abstract_type_refused(const NodeId& typeDefinition)
{
  return StatusCode{Status::BadTypeDefinitionInvalid,
    ErrorDetail::build("InstantiateAbstractType",
      "An abstract type has no instances of its own; instantiate a concrete subtype of it",
      "InstantiationService")
      .context(ContextKeys::nodeId, typeDefinition)};
}

/// Answers whether a Reference of @p referenceType from a type or an InstanceDeclaration can declare a
/// member: HierarchicalReferences or any subtype of it (OPC 10000-3 section 6.2.1), which takes in
/// Organizes, HasAddIn, HasNotifier and every companion subtype, not only the three Aggregates the walk
/// once named. HasSubtype, a hierarchical type, is the exception: its target is a type, never an
/// InstanceDeclaration, and following it would visit every subtype of BaseObjectType.
void declares_member_async(AddressSpace addressSpace, std::shared_ptr<node_utils::RefTypeCache> cache,
  NodeId referenceType, std::function<void(BoolResult)> onComplete) noexcept
{
  // OPC 10000-5 fixes the standard ReferenceType hierarchy, so the standard answers need no walk, and
  // hold in an address space that has not loaded NS0's ReferenceType Nodes.
  static constexpr std::array<ReferenceTypeId, 9> standardHierarchical{
    ReferenceTypeId::HierarchicalReferences,
    ReferenceTypeId::HasChild,
    ReferenceTypeId::Aggregates,
    ReferenceTypeId::HasComponent,
    ReferenceTypeId::HasProperty,
    ReferenceTypeId::HasOrderedComponent,
    ReferenceTypeId::Organizes,
    ReferenceTypeId::HasEventSource,
    ReferenceTypeId::HasNotifier};
  for (const auto standard : standardHierarchical)
  {
    if (referenceType == NodeId{standard})
    {
      onComplete(BoolResult{true});
      return;
    }
  }
  const EncodingLimits limits{.execution = addressSpace.limits()};
  node_utils::is_ref_of_type_cached_async(limits,
    addressSpace,
    /*allowSubTypes=*/true,
    referenceType,
    NodeId{ReferenceTypeId::HasSubtype},
    cache,
    // Held weakly while the namespace answers the first walk (COMP-SVR-NAMESPACE-CALLS-21 rule 1).
    [limits, weakSpace = addressSpace.weak(), cache, referenceType, onComplete = std::move(onComplete)](
      BoolResult isSubtypeReference) mutable
    {
      if (!isSubtypeReference.is_good())
      {
        onComplete(isSubtypeReference.is_bad()
                     ? std::move(isSubtypeReference)
                     : BoolResult{::ua::detail::lookup_failure(
                         referenceType, isSubtypeReference.status_code(), "InstantiationService")});
        return;
      }
      if (isSubtypeReference.value())
      {
        onComplete(BoolResult{false});
        return;
      }
      auto owner = weakSpace.lock();
      if (!owner)
      {
        onComplete(BoolResult{::ua::detail::address_space_gone("InstantiationService")});
        return;
      }
      node_utils::is_ref_of_type_cached_async(limits,
        std::move(*owner),
        /*allowSubTypes=*/true,
        std::move(referenceType),
        NodeId{ReferenceTypeId::HierarchicalReferences},
        std::move(cache),
        std::move(onComplete));
    });
}

/// Answers the NodeId of the instance's hierarchical child with the given browse name, or nothing when it
/// has none.
///
/// @see ua::async::SelfOwningOperation
class InstanceChildNamedOperation final : public ua::async::SelfOwningOperation<InstanceChildNamedOperation>
{
public:
  InstanceChildNamedOperation(AddressSpace addressSpace, NodeId instance, QualifiedName browseName,
    std::shared_ptr<node_utils::RefTypeCache> referenceTypeCache,
    std::function<void(OptionalNodeIdResult)> onComplete)
    : ua::async::SelfOwningOperation<InstanceChildNamedOperation>(
        boost::asio::make_strand(addressSpace.executor()), addressSpace.logger()),
      mAddressSpace(addressSpace.weak()), mInstance(std::move(instance)), mBrowseName(std::move(browseName)),
      mReferenceTypeCache(std::move(referenceTypeCache)), mOnComplete(std::move(onComplete))
  {}

  static void start(AddressSpace addressSpace, NodeId instance, QualifiedName browseName,
    std::shared_ptr<node_utils::RefTypeCache> referenceTypeCache,
    std::function<void(OptionalNodeIdResult)> onComplete)
  {
    launch(std::make_shared<InstanceChildNamedOperation>(std::move(addressSpace),
      std::move(instance),
      std::move(browseName),
      std::move(referenceTypeCache),
      std::move(onComplete)));
  }

private:
  friend class ua::async::SelfOwningOperation<InstanceChildNamedOperation>;

  ua::async::Task<> run()
  {
    try
    {
      auto found = co_await await_step<NodeAccessorResult>(
        [this](auto completion) { find_node_weak(mAddressSpace, mInstance, std::move(completion)); });

      if (!found.is_good())
      {
        refuse(::ua::detail::lookup_failure(mInstance, found.status_code(), "InstantiationService"));
        co_return;
      }

      auto instance = std::move(found).value();
      auto referencesResult = co_await await_step<NodeAccessor::ReferencesResult>(
        [&instance](auto completion) { instance.get_references_async(std::move(completion)); });

      if (!referencesResult.is_good())
      {
        refuse(::ua::detail::references_failure(referencesResult.status_code(), "InstantiationService"));
        co_return;
      }

      // A LOOP, where the chain needed a `step_iteration` trampoline and said why: an inline
      // `find_node_async` would otherwise recurse through `on_candidate_resolved` and overflow the
      // stack on a long reference list. `await_step` posts each answer, so the bound is kept and the
      // recursion is gone.
      const ua::References references = std::move(referencesResult).value();
      for (const auto& reference : references.span())
      {
        if (!reference.is_forward() || reference.is_remote())
        {
          continue;
        }

        auto isMember = co_await await_step<BoolResult>(
          [this, &reference](auto completion)
          {
            auto locked = mAddressSpace.lock();
            if (!locked)
            {
              completion(BoolResult{instantiation_address_space_gone()});
              return;
            }
            declares_member_async(*locked, mReferenceTypeCache, reference.type_id(), std::move(completion));
          });
        if (!isMember.is_good())
        {
          fail(isMember.status_code(), isMember.shared_detail());
          co_return;
        }
        if (!isMember.value())
        {
          continue;
        }

        auto candidate = co_await await_step<NodeAccessorResult>([this, &reference](auto completion)
          { find_node_weak(mAddressSpace, reference.target_id().node_id(), std::move(completion)); });

        // Best-effort: a candidate that will not resolve is skipped rather than failing the answer.
        if (candidate.is_good() && candidate.value().get_browse_name() == mBrowseName)
        {
          complete(OptionalNodeIdResult{optional<NodeId>{reference.target_id().node_id()}});
          co_return;
        }
      }

      complete(OptionalNodeIdResult{optional<NodeId>{}});
    }
    catch (const ua::async::Abandoned&)
    {
      ua::detail::ignore_expected_exception();
    }
    catch (...)
    {
      const VoidResult bad = ua::exception_to_status_code(std::current_exception());
      fail(bad.status_code(), bad.shared_detail());
    }
  }

  void fail_to_start(StatusCode status)
  {
    fail(status, status.shared_detail());
  }

  /// Answers @p status, a refusal of an answer that is not Good, with its detail.
  void refuse(const StatusCode& status)
  {
    fail(status, status.shared_detail());
  }

  void complete(OptionalNodeIdResult result)
  {
    if (auto onComplete = std::move(mOnComplete))
    {
      onComplete(std::move(result));
    }
  }

  void fail(StatusCode status, std::shared_ptr<const ErrorDetail> detail)
  {
    complete(OptionalNodeIdResult{status, std::move(detail)});
  }

  WeakAddressSpace mAddressSpace;
  NodeId mInstance;
  QualifiedName mBrowseName;
  std::shared_ptr<node_utils::RefTypeCache> mReferenceTypeCache;
  std::function<void(OptionalNodeIdResult)> mOnComplete;
};

void instance_child_named_async(AddressSpace addressSpace, NodeId instance, QualifiedName browseName,
  std::shared_ptr<node_utils::RefTypeCache> referenceTypeCache,
  std::function<void(OptionalNodeIdResult)> onComplete) noexcept
{
  InstanceChildNamedOperation::start(std::move(addressSpace),
    std::move(instance),
    std::move(browseName),
    std::move(referenceTypeCache),
    std::move(onComplete));
}

/// Walks a type's InstanceDeclarations and plans the members they give an instance (NR-31): nothing is
/// created here. Each member planned is a Node to create, its HasTypeDefinition, and the link to its parent
/// in both directions, in the instantiation's context; @ref ApplyPlanOperation creates them all once the walk
/// has ended.
///
/// Three passes, in order: the forward hierarchical children (each planned, then recursed into), the
/// non-hierarchical HasCondition references (planned onto the instance), and the supertypes (each walked so
/// inherited declarations are planned too). Recursion is a new InstantiateChildrenOperation per level, and
/// mBudget bounds its depth.
///
/// Which failures are fatal is not uniform, and the distinctions are carried over from the flow this
/// replaces rather than tidied:
///   - resolving the type node, its references, a child's type definition and every recursion are FATAL,
///     and so are the inverse child link and the HasCondition copies when they are added;
///   - the modelling-rule filter's type definition, the existing-child check, the HasTypeDefinition, the
///     forward instance link and the Value copy are BEST-EFFORT.
class InstantiateChildrenOperation final : public ua::async::SelfOwningOperation<InstantiateChildrenOperation>
{
public:
  /// @param ownerTypeDefinition Type definition of @p instance itself. It differs from @p typeDefinition
  ///                            while a supertype's declarations are walked, and is what the optional
  ///                            filter is told the new children's parent type is.
  static void start(AddressSpace addressSpace, DepthBudget budget, NodeId typeDefinition,
    NodeId ownerTypeDefinition, NodeId instance, NodeIdAllocator allocator,
    std::optional<uint16_t> targetNamespaceIndex, OptionalChildFilter optionalFilter,
    std::shared_ptr<instantiation_detail::InstantiationContext> context, bool instantiateNestedTypeOptionals,
    std::function<void(VoidResult)> onComplete)
  {
    // launch() posts the body, which is what the hand-rolled flow had to arrange explicitly at every
    // recursion site: an in-memory namespace answers inline, so a sub-flow started directly would
    // pile a stack frame per nested type level.
    launch(std::make_shared<InstantiateChildrenOperation>(std::move(addressSpace),
      budget,
      std::move(typeDefinition),
      std::move(ownerTypeDefinition),
      std::move(instance),
      std::move(allocator),
      targetNamespaceIndex,
      std::move(optionalFilter),
      std::move(context),
      instantiateNestedTypeOptionals,
      std::move(onComplete)));
  }

  InstantiateChildrenOperation(AddressSpace addressSpace, DepthBudget budget, NodeId typeDefinition,
    NodeId ownerTypeDefinition, NodeId instance, NodeIdAllocator allocator,
    std::optional<uint16_t> targetNamespaceIndex, OptionalChildFilter optionalFilter,
    std::shared_ptr<instantiation_detail::InstantiationContext> context, bool instantiateNestedTypeOptionals,
    std::function<void(VoidResult)> onComplete)
    : ua::async::SelfOwningOperation<InstantiateChildrenOperation>(
        boost::asio::make_strand(addressSpace.executor()), addressSpace.logger()),
      mAddressSpace(addressSpace.weak()), mBudget(budget), mTypeDefinition(std::move(typeDefinition)),
      mOwnerTypeDefinition(std::move(ownerTypeDefinition)), mInstance(std::move(instance)),
      mAllocator(std::move(allocator)), mTargetNamespaceIndex(targetNamespaceIndex),
      mOptionalFilter(std::move(optionalFilter)),
      mInstantiateNestedTypeOptionals(instantiateNestedTypeOptionals), mContext(std::move(context)),
      mOnComplete(std::move(onComplete))
  {}

private:
  friend class ua::async::SelfOwningOperation<InstantiateChildrenOperation>;

  /// Carries one candidate declaration through the per-child steps. Was nine `m`-prefixed members
  /// reset by `advance_forward_iteration`; it is now a local whose lifetime is the loop body.
  struct Candidate
  {
    NodeId refType;
    NodeId targetTypeId;
    std::optional<NodeAccessor> declaration;  // NodeAccessor is not default-constructible
    NodeClass nodeClass{NodeClass::Object};
    QualifiedName browseName;
    std::optional<NodeId> typeDefinition;
    // The declared type was abstract and typeDefinition is the concrete subtype the caller named (D-26).
    bool typeSubstituted{false};
    NodeId childId;
  };

  // Declared ahead of the body that co_awaits them: an `auto` return type has to be deduced before a
  // caller can name it.
  auto find_node(NodeId nodeId)
  {
    return await_step<NodeAccessorResult>([this, nodeId = std::move(nodeId)](auto completion) mutable
      { find_node_weak(mAddressSpace, nodeId, std::move(completion)); });
  }

  /// @param node Borrowed for the call only - the initiate runs synchronously, inside await_ready.
  auto get_references(NodeAccessor& node)
  {
    return await_step<NodeAccessor::ReferencesResult>(
      [&node](auto completion) mutable { node.get_references_async(std::move(completion)); });
  }

  auto declares_member(NodeId referenceType)
  {
    return await_step<BoolResult>(
      [this, referenceType = std::move(referenceType)](auto completion) mutable
      {
        auto locked = mAddressSpace.lock();
        if (!locked)
        {
          completion(BoolResult{instantiation_address_space_gone()});
          return;
        }
        declares_member_async(
          *locked, mContext->reference_type_cache(), std::move(referenceType), std::move(completion));
      });
  }

  auto modelling_rule(NodeAccessor& declaration)
  {
    return await_step<OptionalNodeIdResult>([&declaration](auto completion) mutable
      { get_modelling_rule_async(declaration, std::move(completion)); });
  }

  auto type_definition_id(NodeAccessor& declaration)
  {
    return await_step<OptionalNodeIdResult>([&declaration](auto completion) mutable
      { get_type_definition_id_async(declaration, std::move(completion)); });
  }

  auto instance_child_named(const QualifiedName& browseName)
  {
    return await_step<OptionalNodeIdResult>(
      [this, browseName](auto completion) mutable
      {
        auto locked = mAddressSpace.lock();
        if (!locked)
        {
          completion(OptionalNodeIdResult{instantiation_address_space_gone()});
          return;
        }
        instance_child_named_async(
          *locked, mInstance, browseName, mContext->reference_type_cache(), std::move(completion));
      });
  }

  auto is_reference_of_type(NodeId referenceType, NodeId ofType)
  {
    return await_step<BoolResult>(
      [this, referenceType = std::move(referenceType), ofType = std::move(ofType)](auto completion) mutable
      {
        auto locked = mAddressSpace.lock();
        if (!locked)
        {
          completion(BoolResult{instantiation_address_space_gone()});
          return;
        }
        node_utils::is_ref_of_type_cached_async(EncodingLimits{.execution = locked->limits()},
          *locked,
          /*allowSubTypes=*/true,
          std::move(referenceType),
          std::move(ofType),
          mContext->reference_type_cache(),
          std::move(completion));
      });
  }

  /// Recurses into @p typeDefinition under @p instance, offering Optional members to @p optionalFilter; an
  /// empty one creates only the Mandatory members. The sub-operation's own `launch` posts, so the stack does
  /// not grow across nested type levels however the namespace answers.
  auto recurse_with_filter(
    NodeId typeDefinition, NodeId ownerTypeDefinition, NodeId instance, OptionalChildFilter optionalFilter)
  {
    return await_step<VoidResult>(
      [this,
        typeDefinition = std::move(typeDefinition),
        ownerTypeDefinition = std::move(ownerTypeDefinition),
        instance = std::move(instance),
        optionalFilter = std::move(optionalFilter)](auto completion) mutable
      {
        auto locked = mAddressSpace.lock();
        if (!locked)
        {
          completion(VoidResult{instantiation_address_space_gone()});
          return;
        }
        InstantiateChildrenOperation::start(*locked,
          mBudget,
          std::move(typeDefinition),
          std::move(ownerTypeDefinition),
          std::move(instance),
          mAllocator,
          mTargetNamespaceIndex,
          std::move(optionalFilter),
          mContext,
          mInstantiateNestedTypeOptionals,
          std::move(completion));
      });
  }

  /// Recurses into @p typeDefinition under @p instance with the caller's filter.
  auto recurse(NodeId typeDefinition, NodeId ownerTypeDefinition, NodeId instance)
  {
    return recurse_with_filter(
      std::move(typeDefinition), std::move(ownerTypeDefinition), std::move(instance), mOptionalFilter);
  }

  ua::async::Task<> run()
  {
    try
    {
      mContext->record_type(mTypeDefinition, mInstance);
      mBudget.consume();

      auto typeResult = co_await find_node(mTypeDefinition);
      if (!typeResult.is_good())
      {
        refuse(
          ::ua::detail::lookup_failure(mTypeDefinition, typeResult.status_code(), "InstantiationService"));
        co_return;
      }
      auto typeNode = std::move(typeResult).value();

      auto referencesResult = co_await get_references(typeNode);
      if (!referencesResult.is_good())
      {
        refuse(::ua::detail::references_failure(referencesResult.status_code(), "InstantiationService"));
        co_return;
      }
      mTypeRefs = std::move(referencesResult).value();

      if (!co_await instantiate_forward_children())
      {
        co_return;  // already answered
      }
      if (!co_await copy_condition_references())
      {
        co_return;
      }
      if (!co_await walk_supertypes())
      {
        co_return;
      }

      answer(VoidResult{});
    }
    catch (const ua::async::Abandoned&)
    {
      fail(StatusCode{Status::BadOperationAbandoned}, nullptr);
    }
    catch (...)
    {
      const VoidResult bad = ua::exception_to_status_code(std::current_exception());
      fail(bad.status_code(), bad.shared_detail());
    }
  }

  /// @return false when the operation has already answered with a failure.
  ua::async::Task<bool> instantiate_forward_children()
  {
    for (size_t index = 0; index < mTypeRefs.size(); ++index)
    {
      const auto& reference = mTypeRefs.span()[index];
      if (!reference.is_forward() || reference.is_remote())
      {
        continue;
      }
      if (!reference.target_id().is_local())
      {
        continue;
      }
      const auto referenceType = reference.type_id();
      auto isMember = co_await declares_member(referenceType);
      if (!isMember.is_good())
      {
        fail(isMember.status_code(), isMember.shared_detail());
        co_return false;
      }
      if (!isMember.value())
      {
        continue;
      }

      mBudget.consume();

      // Copied out of the span before the first suspension: the reference is a view into mTypeRefs,
      // and nothing should depend on that staying addressable across an await.
      Candidate candidate;
      candidate.refType = referenceType;
      candidate.targetTypeId = reference.target_id().node_id();

      if (!co_await instantiate_child(candidate))
      {
        co_return false;
      }
    }
    co_return true;
  }

  /// @return false when the operation has already answered with a failure.
  ua::async::Task<bool> instantiate_child(Candidate& candidate)
  {
    auto declarationResult = co_await find_node(candidate.targetTypeId);
    if (!declarationResult.is_good())
    {
      refuse(::ua::detail::lookup_failure(
        candidate.targetTypeId, declarationResult.status_code(), "InstantiationService"));
      co_return false;
    }
    candidate.declaration.emplace(std::move(declarationResult).value());
    candidate.nodeClass = candidate.declaration->get_node_class();
    candidate.browseName = candidate.declaration->get_browse_name();

    // The declaration's name becomes the instantiated child's BrowseName and seeds its allocated
    // NodeId, so a declaration carrying no name would not merely be unreadable - it would create an
    // equally nameless child. `get_browse_name` answers rather than throwing, so refuse here.
    if (candidate.browseName.name().empty())
    {
      fail(StatusCode{Status::BadNodeIdUnknown,
             ErrorDetail::build("InstantiateDeclarationHasNoBrowseName",
               "An InstanceDeclaration carries no BrowseName, so the child it would create cannot be "
               "named",
               "InstantiationService")},
        nullptr);
      co_return false;
    }

    auto ruleResult = co_await modelling_rule(*candidate.declaration);
    if (!ruleResult.is_good())
    {
      fail(ruleResult.status_code(), ruleResult.shared_detail());
      co_return false;
    }
    const auto& modellingRule = ruleResult.value();
    // A placeholder names no member: the instance's own members take instance-specific BrowseNames
    // (OPC 10000-3 sections 6.4.4.4.4 and 6.4.4.4.5), so it is neither offered nor created.
    if (modellingRule.has_value() &&
        (*modellingRule == NodeId{ObjectId::ModellingRule_OptionalPlaceholder} ||
          *modellingRule == NodeId{ObjectId::ModellingRule_MandatoryPlaceholder}))
    {
      co_return true;
    }
    // An ExposesItsArray declaration stands for one Variable per element of its owner's array, whose
    // BrowseNames the rule does not define (OPC 10000-3 section 6.4.4.4.3); it is not one Optional member,
    // so it is neither offered nor created. Creating the per-element Variables needs the array's length.
    if (modellingRule.has_value() && *modellingRule == NodeId{ObjectId::ModellingRule_ExposesItsArray})
    {
      co_return true;
    }
    // A target with no ModellingRule is not an InstanceDeclaration (OPC 10000-3 section 6.2.1), but it is
    // offered like an Optional one (D-23): NS0 gives ConditionType.SupportsFilteredRetain no ModellingRule,
    // and the conditions filter accepts it.
    const bool isMandatory =
      modellingRule.has_value() && *modellingRule == NodeId{ObjectId::ModellingRule_Mandatory};

    if (!isMandatory)
    {
      // An optional child must be offered to the caller's filter; with no filter there is nothing to
      // accept it, so it is skipped entirely.
      if (!mOptionalFilter)
      {
        co_return true;
      }
      // Best-effort: the filter info's type-definition slot tolerates a missing one (pre-flip used
      // `is_good() && value()` and silently fell back to NodeId{}).
      auto filterTypeDef = co_await type_definition_id(*candidate.declaration);
      const optional<NodeId>* const resolved = filterTypeDef.is_good() ? &filterTypeDef.value() : nullptr;
      const ChildFilterInfo info{candidate.browseName,
        candidate.nodeClass,
        resolved && *resolved ? **resolved : NodeId{},
        mOwnerTypeDefinition};
      if (!mOptionalFilter(info))
      {
        co_return true;
      }
    }

    // A member this instantiation planned under the instance, or, for an instance that existed before it, one
    // the instance has. Best-effort: a bad result is treated the same as "does not exist" and planning
    // proceeds, which is what the pre-flip `is_good() && value()` condition did.
    std::optional<NodeId> existingMember = mContext->planned_child(mInstance, candidate.browseName);
    if (!existingMember && !mContext->planned(mInstance))
    {
      auto existing = co_await instance_child_named(candidate.browseName);
      if (existing.is_good())
      {
        const auto& existingChild = existing.value();
        if (existingChild.has_value())
        {
          existingMember = existingChild.value();
        }
      }
    }
    if (existingMember)
    {
      co_return co_await merge_into_member(candidate, *existingMember);
    }

    // The member's type, decided before anything is created so a refusal leaves nothing behind. Fatal,
    // as the pre-flip lookup was.
    auto childTypeDef = co_await type_definition_id(*candidate.declaration);
    if (!childTypeDef.is_good())
    {
      fail(childTypeDef.status_code(), childTypeDef.shared_detail());
      co_return false;
    }
    candidate.typeDefinition = childTypeDef.value();
    if (candidate.typeDefinition)
    {
      auto concrete = co_await concrete_member_type(candidate);
      if (!concrete.is_good())
      {
        fail(concrete.status_code(), concrete.shared_detail());
        co_return false;
      }
      candidate.typeSubstituted = concrete.value() != *candidate.typeDefinition;
      candidate.typeDefinition = concrete.value();
    }

    const auto childNamespaceIndex =
      resolve_target_namespace_index(mTargetNamespaceIndex, mInstance.namespace_index());
    candidate.childId = allocate_node_id(mAllocator, childNamespaceIndex, candidate.browseName);

    // Create-with-attributes (interface refactor 5.2): the child's static attributes are all known now
    // (copied from the resident declaration plus its own browse name), so they are planned with its
    // creation. A Variable's Value is copied from its declaration once it exists.
    mContext->plan_node(instantiation_detail::PlannedNode{
      NodeCreation{candidate.childId,
        candidate.nodeClass,
        build_child_initial_attributes(*candidate.declaration, candidate.nodeClass, candidate.browseName)},
      candidate.nodeClass == NodeClass::Variable ? candidate.declaration : std::nullopt});
    if (candidate.typeDefinition)
    {
      mContext->plan_half(instantiation_detail::PlannedHalf{ReferenceChange{candidate.childId,
                                                              NodeId{ReferenceTypeId::HasTypeDefinition},
                                                              ExpandedNodeId{*candidate.typeDefinition},
                                                              true,
                                                              true},
        false});
    }
    mContext->plan_link(mInstance, candidate.refType, candidate.childId, candidate.browseName);
    mContext->record_node(instantiation_detail::InstantiatedNodeBinding{candidate.targetTypeId,
      candidate.childId,
      mInstance,
      candidate.refType,
      candidate.browseName,
      candidate.nodeClass,
      candidate.typeDefinition});

    // Recurse into this child's own declaration to instantiate its mandatory children.
    const NodeId childOwnerType =
      candidate.typeDefinition ? *candidate.typeDefinition : candidate.targetTypeId;
    auto recursed = co_await recurse(candidate.targetTypeId, childOwnerType, candidate.childId);
    if (recursed.is_bad())
    {
      fail(recursed.status_code(), recursed.shared_detail());
      co_return false;
    }

    // The recursion above walked the child's instance DECLARATION, which only redeclares the subset
    // of children the declaring type chose to surface (e.g. EnabledState's Id). Type-level OPTIONAL
    // children declared on the child's TYPE DEFINITION but not redeclared on the instance declaration
    // - e.g. TwoStateVariableType.TransitionTime under a Condition's EnabledState - are otherwise
    // never seen by the optional-child filter. Walk the type definition too so they are offered to
    // it. Idempotent: the existing-child check skips anything the declaration walk already made.
    // A substituted concrete type is walked too: its own members (NetworkAddressUrlType's Url) are on no
    // declaration of the instantiated type. Its Optional members are offered to the filter only under
    // instantiateNestedTypeOptionals, as for any member's type; otherwise only its Mandatory members are
    // made.
    if ((mInstantiateNestedTypeOptionals || candidate.typeSubstituted) && candidate.typeDefinition &&
        *candidate.typeDefinition != candidate.targetTypeId)
    {
      OptionalChildFilter typeFilter;
      if (mInstantiateNestedTypeOptionals)
        typeFilter = mOptionalFilter;
      auto recursedType = co_await recurse_with_filter(
        *candidate.typeDefinition, childOwnerType, candidate.childId, std::move(typeFilter));
      if (recursedType.is_bad())
      {
        fail(recursedType.status_code(), recursedType.shared_detail());
        co_return false;
      }
    }

    co_return true;
  }

  /// The type a member is created with (D-26). OPC 10000-3 section 6.2.1: "The type of an
  /// InstanceDeclaration may be abstract, however the instance must be of a concrete type." A concrete
  /// declared type, or one that cannot be read, is used as it is. An abstract one is replaced by the
  /// concrete subtype InstantiationOptions::memberTypeResolver names; with no answer, or an answer that is
  /// not a concrete subtype of the declared type with the same NodeClass, the instantiation is refused with
  /// Bad_TypeDefinitionInvalid. The SDK never chooses a subtype itself. A declared or named type whose lookup
  /// is answered Uncertain is refused (`LookupAnswerUncertain`): what the type is decides the rule.
  ua::async::Task<Result<NodeId>> concrete_member_type(const Candidate& candidate)
  {
    const NodeId declaredType = *candidate.typeDefinition;
    auto typeNode = co_await find_node(declaredType);
    if (typeNode.is_uncertain())
    {
      co_return Result<NodeId>{
        ::ua::detail::lookup_failure(declaredType, typeNode.status_code(), "InstantiationService")};
    }
    if (!typeNode.is_good() || !is_abstract_type(typeNode.value()))
    {
      co_return Result<NodeId>{declaredType};
    }

    std::optional<NodeId> named;
    if (mContext->memberTypeResolver)
    {
      named = mContext->memberTypeResolver(
        ChildFilterInfo{candidate.browseName, candidate.nodeClass, declaredType, mOwnerTypeDefinition});
    }
    if (!named)
    {
      co_return Result<NodeId>{StatusCode{Status::BadTypeDefinitionInvalid,
        ErrorDetail::build("MemberTypeAbstract",
          "A member's declared type is abstract and no concrete subtype was named for it; "
          "InstantiationOptions::memberTypeResolver names one",
          "InstantiationService")
          .context(ContextKeys::nodeId, candidate.targetTypeId)
          .context(ContextKeys::typeExpected, declaredType)}};
    }

    bool concreteSubtype = false;
    auto namedNode = co_await find_node(*named);
    if (namedNode.is_uncertain())
    {
      co_return Result<NodeId>{
        ::ua::detail::lookup_failure(*named, namedNode.status_code(), "InstantiationService")};
    }
    if (namedNode.is_good() && !is_abstract_type(namedNode.value()) &&
        namedNode.value().get_node_class() == typeNode.value().get_node_class())
    {
      auto subtype = co_await is_reference_of_type(*named, declaredType);
      concreteSubtype = subtype.is_good() && subtype.value();
    }
    if (!concreteSubtype)
    {
      co_return Result<NodeId>{StatusCode{Status::BadTypeDefinitionInvalid,
        ErrorDetail::build("MemberTypeNotAConcreteSubtype",
          "The type named for a member is not a concrete subtype of the member's declared type",
          "InstantiationService")
          .context(ContextKeys::nodeId, candidate.targetTypeId)
          .context(ContextKeys::typeExpected, declaredType)
          .context(ContextKeys::typeActual, *named)}};
    }
    co_return Result<NodeId>{*named};
  }

  /// OPC 10000-3 section 6.3.3.2, Table 19: the fully-inherited InstanceDeclarationHierarchy merges a
  /// supertype's declaration into the member an override created. The member gets the supertype's
  /// hierarchical Reference, unless the instance already references it with that ReferenceType or a
  /// subtype of it (section 6.3.3.3), and the members declared under the supertype's declaration. A member
  /// this instantiation did not create, one that was there before it began, is left as it is.
  ///
  /// @return false when the operation has already answered with a failure.
  ua::async::Task<bool> merge_into_member(Candidate& candidate, NodeId member)
  {
    if (!mContext->created(member))
    {
      co_return true;
    }

    // The member was created by this instantiation, so every link to it is planned.
    bool referenced = false;
    for (const auto& linkType : mContext->planned_link_types(mInstance, member))
    {
      auto sameType = co_await is_reference_of_type(linkType, candidate.refType);
      if (sameType.is_good() && sameType.value())
      {
        referenced = true;
        break;
      }
    }

    if (!referenced)
    {
      // As for a created member: the forward half is best-effort, its mirror on the member required.
      mContext->plan_link(mInstance, candidate.refType, member, candidate.browseName);
    }

    auto typeDefinition = co_await type_definition_id(*candidate.declaration);
    NodeId ownerType = candidate.targetTypeId;
    if (typeDefinition.is_good())
    {
      const auto& ownerTypeDefinition = typeDefinition.value();
      if (ownerTypeDefinition.has_value())
      {
        ownerType = ownerTypeDefinition.value();
      }
    }
    auto recursed = co_await recurse(candidate.targetTypeId, ownerType, member);
    if (recursed.is_bad())
    {
      fail(recursed.status_code(), recursed.shared_detail());
      co_return false;
    }
    co_return true;
  }

  /// @return false when the operation has already answered with a failure.
  ua::async::Task<bool> copy_condition_references()
  {
    std::vector<Reference> conditionReferences;
    for (const auto& reference : mTypeRefs.span())
    {
      if (reference.is_forward() && reference.type_id() == NodeId{ReferenceTypeId::HasCondition})
      {
        conditionReferences.push_back(reference);
      }
    }
    // Required, as the copy was fatal in the per-member flow; planned as the instance's own halves.
    for (const auto& reference : conditionReferences)
    {
      mContext->plan_half(instantiation_detail::PlannedHalf{
        ReferenceChange{
          mInstance, reference.type_id(), reference.target_id(), true, mContext->planned(mInstance)},
        true});
    }
    co_return true;
  }

  /// @return false when the operation has already answered with a failure.
  ua::async::Task<bool> walk_supertypes()
  {
    for (size_t index = 0; index < mTypeRefs.size(); ++index)
    {
      const auto& reference = mTypeRefs.span()[index];
      if (reference.is_forward() || reference.is_remote())
      {
        continue;
      }
      if (reference.type_id() != NodeId{ReferenceTypeId::HasSubtype})
      {
        continue;
      }
      const auto parentTypeId = reference.target_id().node_id();
      auto recursed = co_await recurse(parentTypeId, mOwnerTypeDefinition, mInstance);
      if (recursed.is_bad())
      {
        fail(recursed.status_code(), recursed.shared_detail());
        co_return false;
      }
    }
    co_return true;
  }

  // Builds the child instance's create-time attribute set (create-with-attributes, interface refactor
  // 5.2): its own BrowseName/DisplayName plus the static class-specific and Part-18 security
  // attributes copied verbatim - in wire form, no domain round-trip - from the resident declaration.
  // Replaces the former create-then-setter-burst, so a possibly-remote owning namespace is built in
  // one op with no strand-blocking sync writes.
  ua::InitialAttributes build_child_initial_attributes(
    const NodeAccessor& declaration, NodeClass nodeClass, const QualifiedName& browseName) const
  {
    ua::InitialAttributes attributes = make_browse_display_attributes(browseName);

    // For the OPTIONAL Part-18 security attributes, copy from the declaration only when set there -
    // read_attribute returns the stored wire form verbatim, and skip-if-empty matches the previous
    // get_role_permissions()/get_access_restrictions() optional checks (which set only when present).
    auto copyFromDeclaration = [&](AttributeId attributeId)
    {
      auto value = declaration.read_attribute(attributeId);
      if (!value.empty())
      {
        attributes.emplace_back(attributeId, std::move(value));
      }
    };

    if (nodeClass == NodeClass::Variable)
    {
      // Use the typed declaration getters + single-source encoders. The getters throw on an unset
      // mandatory attribute (read_attribute(X).as<T>() on an empty Variant), exactly as the previous
      // set_X(varDecl->get_X()) burst did - caught at the create site, failing the instantiation
      // rather than silently producing a Variable instance with no DataType/ValueRank/AccessLevel.
      // The Variable's live Value is NOT a stored attribute (only VariableType carries a stored
      // default); an instance Variable's value lives in its value source and is copied asynchronously
      // via the value pipeline (ApplyPlanOperation), never as a creation attribute.
      if (auto variableDeclaration = declaration.as<VariableAccessor>())
      {
        attributes.emplace_back(
          AttributeId::DataType, attribute_wire::data_type(variableDeclaration->get_data_type()));
        attributes.emplace_back(
          AttributeId::ValueRank, attribute_wire::value_rank(variableDeclaration->get_value_rank()));
        attributes.emplace_back(
          AttributeId::AccessLevel, attribute_wire::access_level(variableDeclaration->get_access_level()));
      }
    }
    else if (nodeClass == NodeClass::Method)
    {
      // Executable defaults to true when a declaration leaves it unset (MethodAccessor::get_executable),
      // and the previous set_executable(get_executable()) wrote that default explicitly - preserve it
      // rather than skipping, so the instance reports the same Executable value.
      auto executable = declaration.read_attribute(AttributeId::Executable);
      attributes.emplace_back(
        AttributeId::Executable, executable.empty() ? Variant{true} : std::move(executable));
    }

    // Inherit Part-18 security attributes from declaration -> instance per Part 3 5.2.9: carries
    // RoleType's admin-only RolePermissions / EncryptionRequired AccessRestrictions through to
    // runtime-instantiated Role objects so AddRole-created custom roles inherit the same surface.
    copyFromDeclaration(AttributeId::RolePermissions);
    copyFromDeclaration(AttributeId::AccessRestrictions);
    return attributes;
  }

  void fail_to_start(StatusCode status)
  {
    fail(status, status.shared_detail());
  }

  /// Answers @p status, a refusal of an answer that is not Good, with its detail.
  void refuse(const StatusCode& status)
  {
    fail(status, status.shared_detail());
  }

  void fail(StatusCode status, std::shared_ptr<const ErrorDetail> detail)
  {
    answer(VoidResult{status, std::move(detail)});
  }

  /// Fires once: a body that failed a step and then unwound must not answer twice.
  void answer(VoidResult result)
  {
    if (auto callback = std::exchange(mOnComplete, nullptr))
    {
      callback(std::move(result));
    }
  }

  // Inputs - captured by value at construction. The address space is held weakly (CALLS-21 rule 1).
  WeakAddressSpace mAddressSpace;
  DepthBudget mBudget;
  NodeId mTypeDefinition;
  NodeId mOwnerTypeDefinition;
  NodeId mInstance;
  NodeIdAllocator mAllocator;
  std::optional<uint16_t> mTargetNamespaceIndex;
  OptionalChildFilter mOptionalFilter;
  // Opt-in: also walk a child's type definition for filter-accepted optional children not redeclared
  // on its instance declaration. Inherited by every sub-operation so the whole subtree shares it.
  bool mInstantiateNestedTypeOptionals{false};
  std::shared_ptr<instantiation_detail::InstantiationContext> mContext;
  std::function<void(VoidResult)> mOnComplete;

  ua::References mTypeRefs;
};

/// Plans the members @p typeDefinition gives @p instance into @p context (InstantiateChildrenOperation).
void plan_children_async(AddressSpace addressSpace, DepthBudget budget, NodeId typeDefinition,
  NodeId instance, NodeIdAllocator allocator, std::optional<uint16_t> targetNamespaceIndex,
  OptionalChildFilter optionalFilter, bool instantiateNestedTypeOptionals,
  std::shared_ptr<instantiation_detail::InstantiationContext> context,
  std::function<void(VoidResult)> onComplete)
{
  auto ownerTypeDefinition = typeDefinition;
  InstantiateChildrenOperation::start(std::move(addressSpace),
    budget,
    std::move(typeDefinition),
    std::move(ownerTypeDefinition),
    std::move(instance),
    std::move(allocator),
    targetNamespaceIndex,
    std::move(optionalFilter),
    std::move(context),
    instantiateNestedTypeOptionals,
    std::move(onComplete));
}

/// Creates what an instantiation's walk planned (NR-31, the instantiation's steps 2 to 5): the declarations'
/// Values are read in one batch, every planned Node is created in one batch, every planned Reference half is
/// added in one batch, and the Values are written in one batch, each one call per namespace per chunk of its
/// operation limit. Each Node created is added to the subtree, so a failure removes what was created. A Node
/// that cannot be created, or a required half that is refused, fails the instantiation; a refused best-effort
/// half and a Value that cannot be read or written do not, as in the per-member flow. A half answered
/// `Bad_DuplicateReferenceNotAllowed` is already held and counts as added (NR-68 item 8).
class ApplyPlanOperation final : public ua::async::SelfOwningOperation<ApplyPlanOperation>
{
public:
  static void start(AddressSpace addressSpace,
    std::shared_ptr<const instantiation_detail::InstantiationContext> context, NodeSubtree* subtree,
    std::function<void(VoidResult)> onComplete)
  {
    launch(std::make_shared<ApplyPlanOperation>(
      std::move(addressSpace), std::move(context), subtree, std::move(onComplete)));
  }

  ApplyPlanOperation(AddressSpace addressSpace,
    std::shared_ptr<const instantiation_detail::InstantiationContext> context, NodeSubtree* subtree,
    std::function<void(VoidResult)> onComplete)
    : ua::async::SelfOwningOperation<ApplyPlanOperation>(
        boost::asio::make_strand(addressSpace.executor()), addressSpace.logger()),
      mAddressSpace(addressSpace.weak()), mContext(std::move(context)), mSubtree(subtree),
      mOnComplete(std::move(onComplete))
  {}

private:
  friend class ua::async::SelfOwningOperation<ApplyPlanOperation>;

  ua::async::Task<> run()
  {
    try
    {
      const auto& nodes = mContext->planned_nodes();

      // The declarations' default Values, read once for every caller.
      std::vector<::ua::detail::ValueRead> reads;
      std::vector<std::size_t> readFor;
      for (std::size_t i = 0; i < nodes.size(); ++i)
      {
        const auto& declaration = nodes[i].declaration;
        if (!declaration)
        {
          continue;
        }
        ReadValueId readValueId;
        readValueId.node_id() = declaration.value().get_node_id();
        readValueId.attribute_id() = utils::to_underlying(AttributeId::Value);
        reads.push_back(::ua::detail::ValueRead{declaration.value(), std::move(readValueId)});
        readFor.push_back(i);
      }
      std::vector<DataValueResult> values;
      if (!reads.empty())
      {
        values = co_await await_step<std::vector<DataValueResult>>(
          [reads = std::move(reads)](auto completion) mutable
          {
            ::ua::detail::NodeAccessorRoute::read_values(RequestInfo{},
              nullptr,
              std::move(reads),
              Duration{},
              /*setSourceTimestamp=*/false,
              std::move(completion));
          });
      }

      auto creations = std::make_shared<std::vector<NodeCreation>>();
      creations->reserve(nodes.size());
      for (const auto& node : nodes)
      {
        creations->push_back(node.creation);
      }
      auto created = co_await await_step<std::vector<NodeAccessorResult>>(
        [this, creations](auto completion) mutable
        {
          ::ua::detail::NodeAccessorRoute::create_nodes(
            mAddressSpace, RequestInfo{}, creations, std::move(completion));
        });
      if (created.size() != nodes.size())
      {
        fail(StatusCode{Status::BadInternalError}, nullptr);
        co_return;
      }
      std::optional<StatusCode> refused;
      for (std::size_t i = 0; i < created.size(); ++i)
      {
        // A Node the namespace holds is removed again if the instantiation fails, an Uncertain answer's too.
        if (created[i].has_value())
        {
          mSubtree->add_created_node(nodes[i].creation.nodeId);
        }
        if (!created[i].is_good() && !refused)
        {
          refused = ::ua::detail::lookup_failure(
            nodes[i].creation.nodeId, created[i].status_code(), "InstantiationService");
        }
      }
      if (refused)
      {
        fail(*refused, refused->shared_detail());
        co_return;
      }

      // The instantiation is one operation (NR-36 rule 4): its event is raised before it answers. A failed
      // one drops the step, which raises what was recorded once its calls have ended; the rollback raises its
      // own.
      auto step = ::ua::detail::NodeAccessorRoute::model_change_step(mAddressSpace);
      const auto& halves = mContext->planned_halves();
      if (!halves.empty())
      {
        auto changes = std::make_shared<std::vector<ReferenceChange>>();
        changes->reserve(halves.size());
        for (const auto& half : halves)
        {
          changes->push_back(half.change);
        }
        auto added = co_await await_step<std::vector<VoidResult>>(
          [this, changes, step](auto completion) mutable
          {
            ::ua::detail::NodeAccessorRoute::add_references(
              mAddressSpace, RequestInfo{}, changes, std::move(completion), /*addRequiredPairs=*/true, step);
          });
        if (added.size() != halves.size())
        {
          fail(StatusCode{Status::BadInternalError}, nullptr);
          co_return;
        }
        for (std::size_t k = 0; k < added.size(); ++k)
        {
          if (added[k].is_good() ||
              added[k].status_code().as_status() == Status::BadDuplicateReferenceNotAllowed ||
              !halves[k].required)
          {
            continue;
          }
          // The instantiation does not stand on a required half the namespace is uncertain it added.
          const StatusCode linkRefused =
            ::ua::detail::answer_failure(added[k].status_code(), "AnswerUncertain", "InstantiationService");
          fail(linkRefused, linkRefused.shared_detail());
          co_return;
        }
      }

      // Only a good, non-empty Value is copied: a value-less declaration, or a bad read, leaves the member
      // with its default-empty value. The Value copy is best-effort, as in the per-member flow.
      std::vector<::ua::detail::ValueWrite> writes;
      for (std::size_t j = 0; j < readFor.size() && j < values.size(); ++j)
      {
        if (!values[j].is_good() || values[j].value().value().empty())
        {
          continue;
        }
        const std::size_t i = readFor[j];
        WriteValue writeValue;
        writeValue.node_id() = nodes[i].creation.nodeId;
        writeValue.attribute_id() = utils::to_underlying(AttributeId::Value);
        writeValue.value() = values[j].value();
        writes.push_back(::ua::detail::ValueWrite{created[i].value(), std::move(writeValue)});
      }
      if (!writes.empty())
      {
        (void)co_await await_step<std::vector<VoidResult>>(
          [writes = std::move(writes), step](auto completion) mutable
          {
            ::ua::detail::NodeAccessorRoute::write_values(
              RequestInfo{}, nullptr, std::move(writes), std::move(completion), step);
          });
      }
      (void)co_await await_step<bool>([&step](auto completion) mutable
        { step->close([completion = std::move(completion)]() mutable { completion(true); }); });
      answer(VoidResult{});
    }
    catch (const ua::async::Abandoned&)
    {
      fail(StatusCode{Status::BadOperationAbandoned}, nullptr);
    }
    catch (...)
    {
      const VoidResult bad = ua::exception_to_status_code(std::current_exception());
      fail(bad.status_code(), bad.shared_detail());
    }
  }

  void fail_to_start(StatusCode status)
  {
    fail(status, status.shared_detail());
  }

  void fail(StatusCode status, std::shared_ptr<const ErrorDetail> detail)
  {
    answer(VoidResult{status, std::move(detail)});
  }

  /// Fires once: a body that failed a step and then unwound must not answer twice.
  void answer(VoidResult result)
  {
    if (auto callback = std::exchange(mOnComplete, nullptr))
    {
      callback(std::move(result));
    }
  }

  WeakAddressSpace mAddressSpace;
  std::shared_ptr<const instantiation_detail::InstantiationContext> mContext;
  NodeSubtree* mSubtree;  // non-owning - owned by the caller's operation
  std::function<void(VoidResult)> mOnComplete;
};

/// Creates what @p context planned (ApplyPlanOperation), then links the external guard Variables the walk
/// recorded (Part 16 section 4.6.5).
void apply_plan_async(AddressSpace addressSpace, DepthBudget budget,
  std::shared_ptr<instantiation_detail::InstantiationContext> context, NodeSubtree* subtree,
  std::function<void(VoidResult)> onComplete)
{
  auto handle = addressSpace.weak();
  ApplyPlanOperation::start(std::move(addressSpace),
    context,
    subtree,
    [handle = std::move(handle), budget, context, onComplete = std::move(onComplete)](
      VoidResult result) mutable
    {
      if (!result.is_good())
      {
        ua::detail::invoke_user_callback(onComplete, std::move(result));
        return;
      }
      auto locked = handle.lock();
      if (!locked)
      {
        ua::detail::invoke_user_callback(onComplete, VoidResult{instantiation_address_space_gone()});
        return;
      }
      instantiation_detail::wire_external_guard_variables_async(
        *locked, budget, std::move(context), std::move(onComplete));
    });
}

/// Instantiates an ObjectType or a VariableType (NR-31): the root's NodeId is allocated, its parent and the
/// parent ReferenceType's Symmetric attribute are looked up, the type's members are planned, and then the
/// root and every member are created, linked and given their Values, one batch each (ApplyPlanOperation). A
/// failure before the batches creates nothing; a failure in them removes what was created.
///
/// Best-effort, as in the flow this replaces: the HasTypeDefinition Reference, both halves of the parent
/// link, the Symmetric lookup that decides the mirror half's direction, and a Variable root's inheritance of
/// DataType and ValueRank from its type. Parent resolution, root creation and member instantiation can fail
/// it.
class InstantiateInstanceOperation final : public ua::async::SelfOwningOperation<InstantiateInstanceOperation>
{
public:
  /// @param variable Engaged for a VariableType: the root is a Variable with these attributes (NR-21 rule 8).
  static void start(AddressSpace addressSpace, DepthBudget budget, NodeId parent, QualifiedName browseName,
    NodeId typeDefinition, InstantiationOptions options,
    std::optional<VariableInstantiationAttributes> variable,
    std::function<void(NodeSubtreeResult)> onComplete)
  {
    launch(std::make_shared<InstantiateInstanceOperation>(std::move(addressSpace),
      budget,
      std::move(parent),
      std::move(browseName),
      std::move(typeDefinition),
      std::move(options),
      std::move(variable),
      std::move(onComplete)));
  }

  InstantiateInstanceOperation(AddressSpace addressSpace, DepthBudget budget, NodeId parent,
    QualifiedName browseName, NodeId typeDefinition, InstantiationOptions options,
    std::optional<VariableInstantiationAttributes> variable,
    std::function<void(NodeSubtreeResult)> onComplete)
    : ua::async::SelfOwningOperation<InstantiateInstanceOperation>(
        boost::asio::make_strand(addressSpace.executor()), addressSpace.logger()),
      mAddressSpace(addressSpace.weak()), mBudget(budget), mParent(std::move(parent)),
      mBrowseName(std::move(browseName)), mTypeDefinition(std::move(typeDefinition)),
      mOptions(std::move(options)), mVariable(std::move(variable)), mOnComplete(std::move(onComplete))
  {}

private:
  friend class ua::async::SelfOwningOperation<InstantiateInstanceOperation>;

  // Declared ahead of the body that co_awaits them: an `auto` return type has to be deduced before
  // a caller can name it.
  auto find_node(NodeId nodeId)
  {
    return await_step<NodeAccessorResult>([this, nodeId = std::move(nodeId)](auto completion) mutable
      { find_node_weak(mAddressSpace, nodeId, std::move(completion)); });
  }

  auto plan_children(std::shared_ptr<instantiation_detail::InstantiationContext> context)
  {
    return await_step<VoidResult>(
      [this, context = std::move(context)](auto completion) mutable
      {
        auto locked = mAddressSpace.lock();
        if (!locked)
        {
          completion(VoidResult{instantiation_address_space_gone()});
          return;
        }
        plan_children_async(*locked,
          mBudget,
          mTypeDefinition,
          mNewId,
          mOptions.nodeIdAllocator,
          mOptions.targetNamespaceIndex,
          mOptions.optionalChildFilter,
          mOptions.instantiateNestedTypeOptionals,
          std::move(context),
          std::move(completion));
      });
  }

  auto apply(std::shared_ptr<instantiation_detail::InstantiationContext> context)
  {
    return await_step<VoidResult>(
      [this, context = std::move(context)](auto completion) mutable
      {
        auto locked = mAddressSpace.lock();
        if (!locked)
        {
          completion(VoidResult{instantiation_address_space_gone()});
          return;
        }
        apply_plan_async(*locked, mBudget, std::move(context), &(*mSubtree), std::move(completion));
      });
  }

  /// The namespace of the root. A direct dictionary entry lives in the namespace OPC 10000-19 fixes for its
  /// type. The service never registers a namespace (API-6.2): an unregistered one is an error naming the URI,
  /// and an explicit target naming any other namespace is refused rather than ignored (API-6.3).
  Result<uint16_t> root_namespace_index()
  {
    const auto dictionaryNamespace = direct_dictionary_namespace(mTypeDefinition);
    if (!dictionaryNamespace)
    {
      return Result<uint16_t>{
        resolve_target_namespace_index(mOptions.targetNamespaceIndex, mParent.namespace_index())};
    }
    auto locked = mAddressSpace.lock();
    if (!locked)
    {
      return Result<uint16_t>{instantiation_address_space_gone()};
    }
    const auto registered = registered_namespace_index(*locked, dictionaryNamespace->uri);
    if (!registered)
    {
      return Result<uint16_t>{StatusCode{Status::BadInvalidState,
        ErrorDetail::build("DictionaryNamespaceNotRegistered",
          "A dictionary entry's namespace must be registered before the entry is instantiated; "
          "instantiation never registers a namespace",
          "InstantiationService")
          .context(ContextKeys::namespaceUri, std::string{dictionaryNamespace->uri})}};
    }
    if (mOptions.targetNamespaceIndex && *mOptions.targetNamespaceIndex != *registered)
    {
      return Result<uint16_t>{StatusCode{Status::BadInvalidArgument,
        ErrorDetail::build("DictionaryEntryNamespaceFixed",
          std::string{dictionaryNamespace->clause} +
            " fixes the namespace of this dictionary entry type; the explicit target namespace names "
            "another",
          "InstantiationService")
          .context(ContextKeys::namespaceUri, std::string{dictionaryNamespace->uri})
          .context(ContextKeys::expected, std::to_string(*registered))
          .context(ContextKeys::actual, std::to_string(*mOptions.targetNamespaceIndex))}};
    }
    return Result<uint16_t>{*registered};
  }

  /// A Variable root's DataType, ValueRank and AccessLevel, given at creation (NR-21 rule 8). A supplied
  /// field OVERRIDES the type; a field left nullopt INHERITS from it, which is what
  /// VariableInstantiationAttributes documents. AccessLevel is not inherited: a VariableType has no
  /// AccessLevel attribute (Part 3 5.6.5).
  void add_variable_attributes(ua::InitialAttributes& attributes, const NodeAccessorResult& rootType) const
  {
    const VariableInstantiationAttributes& given = *mVariable;
    std::optional<VariableTypeAccessor> variableType;
    if (rootType.is_good())
    {
      variableType = rootType.value().as<VariableTypeAccessor>();
    }
    if (given.dataType)
    {
      attributes.emplace_back(AttributeId::DataType, attribute_wire::data_type(*given.dataType));
    }
    else if (variableType)
    {
      attributes.emplace_back(
        AttributeId::DataType, attribute_wire::data_type(variableType->get_data_type()));
    }
    if (given.valueRank)
    {
      attributes.emplace_back(
        AttributeId::ValueRank, attribute_wire::value_rank(ValueRank{*given.valueRank}));
    }
    else if (variableType)
    {
      attributes.emplace_back(
        AttributeId::ValueRank, attribute_wire::value_rank(variableType->get_value_rank()));
    }
    if (given.accessLevel)
    {
      attributes.emplace_back(AttributeId::AccessLevel, attribute_wire::access_level(*given.accessLevel));
    }
  }

  ua::async::Task<> run()
  {
    try
    {
      mBudget.consume();

      // The root is an instance of the type, so the type must be concrete. Whether it is decides the rule,
      // so a lookup answered Uncertain is refused; one that is Bad leaves the rule to the type's walk.
      auto rootType = co_await find_node(mTypeDefinition);
      if (rootType.is_uncertain())
      {
        fail_to_start(
          ::ua::detail::lookup_failure(mTypeDefinition, rootType.status_code(), "InstantiationService"));
        co_return;
      }
      if (rootType.is_good() && is_abstract_type(rootType.value()))
      {
        fail_to_start(abstract_type_refused(mTypeDefinition));
        co_return;
      }

      auto targetNamespaceIndex = root_namespace_index();
      if (!targetNamespaceIndex.is_good())
      {
        fail_to_start(targetNamespaceIndex.status_code());
        co_return;
      }
      if (direct_dictionary_namespace(mTypeDefinition))
      {
        // The root's NodeId is the external dictionary identifier, passed as the BrowseName's name.
        mNewId = NodeId{targetNamespaceIndex.value(), static_cast<string_view>(mBrowseName.name())};
      }
      else
      {
        mNewId = allocate_node_id(mOptions.nodeIdAllocator, targetNamespaceIndex.value(), mBrowseName);
      }

      ua::InitialAttributes attributes = make_browse_display_attributes(mBrowseName);
      if (mVariable)
      {
        add_variable_attributes(attributes, rootType);
      }

      mBudget.consume();

      auto parentResult = co_await find_node(mParent);
      if (!parentResult.is_good())
      {
        const StatusCode refused =
          ::ua::detail::lookup_failure(mParent, parentResult.status_code(), "InstantiationService");
        fail(refused, refused.shared_detail());
        co_return;
      }

      const auto parentRefType = mOptions.parentReferenceType.value_or(NodeId{ReferenceTypeId::HasComponent});

      // The mirror half's direction depends on the parent ReferenceType's Symmetric attribute. An asymmetric
      // type (e.g. HasComponent) is mirrored as an INVERSE half, but a symmetric type (e.g. AssociatedWith)
      // is forward from both ends (OPC 10000-3 5.3.2) and must never be stored or browsed as inverse (OPC
      // 10000-4 5.8.2). Defaulting to asymmetric when the type cannot be resolved is the correct case for
      // every hierarchical type and the prior behaviour; the resolution is best-effort.
      bool symmetric = false;
      auto refTypeResult = co_await find_node(parentRefType);
      if (refTypeResult.is_good())
      {
        if (auto refType = refTypeResult.value().as<ReferenceTypeAccessor>())
        {
          symmetric = refType->get_symmetric();
        }
      }

      auto context = std::make_shared<instantiation_detail::InstantiationContext>();
      context->memberTypeResolver = mOptions.memberTypeResolver;
      context->plan_node(instantiation_detail::PlannedNode{
        NodeCreation{mNewId, mVariable ? NodeClass::Variable : NodeClass::Object, std::move(attributes)},
        std::nullopt});
      // Best-effort, as before: the HasTypeDefinition, and both halves of the parent link. The mirror half on
      // the root lets a later DeleteNodes on it find the parent and remove the parent's forward Reference.
      context->plan_half(instantiation_detail::PlannedHalf{
        ReferenceChange{
          mNewId, NodeId{ReferenceTypeId::HasTypeDefinition}, ExpandedNodeId{mTypeDefinition}, true, true},
        false});
      context->plan_half(instantiation_detail::PlannedHalf{
        ReferenceChange{mParent, parentRefType, ExpandedNodeId{mNewId}, true, false}, false});
      context->plan_half(instantiation_detail::PlannedHalf{
        ReferenceChange{mNewId, parentRefType, ExpandedNodeId{mParent}, symmetric, true}, false});

      mBudget.consume();

      auto planned = co_await plan_children(context);
      if (planned.is_bad())
      {
        fail(planned.status_code(), planned.shared_detail());
        co_return;
      }

      {
        auto locked = mAddressSpace.lock();
        if (!locked)
        {
          fail_to_start(instantiation_address_space_gone());
          co_return;
        }
        mSubtree.emplace(*locked, mNewId, std::vector<NodeId>{});
      }
      auto applied = co_await apply(context);
      if (!applied.is_good())
      {
        // An Uncertain outcome is refused as a Bad one is: the subtree is removed.
        mSubtree->remove_async();
        const StatusCode refused =
          ::ua::detail::answer_failure(applied.status_code(), "AnswerUncertain", "InstantiationService");
        fail(refused, refused.shared_detail());
        co_return;
      }

      auto subtree = std::move(*mSubtree);
      mSubtree.reset();
      answer(NodeSubtreeResult{std::move(subtree)});
    }
    catch (const ua::async::Abandoned&)
    {
      fail(StatusCode{Status::BadOperationAbandoned}, nullptr);
    }
    catch (...)
    {
      const NodeSubtreeResult bad = ua::exception_to_status_code(std::current_exception());
      fail(bad.status_code(), bad.shared_detail());
    }
  }

  void fail_to_start(StatusCode status)
  {
    fail(status, status.shared_detail());
  }

  void fail(StatusCode status, std::shared_ptr<const ErrorDetail> detail)
  {
    mSubtree.reset();
    answer(NodeSubtreeResult{status, std::move(detail)});
  }

  /// Fires once: a body that failed a step and then unwound must not answer twice.
  void answer(NodeSubtreeResult result)
  {
    if (auto callback = std::exchange(mOnComplete, nullptr))
    {
      callback(std::move(result));
    }
  }

  WeakAddressSpace mAddressSpace;
  DepthBudget mBudget;
  NodeId mParent;
  QualifiedName mBrowseName;
  NodeId mTypeDefinition;
  InstantiationOptions mOptions;
  std::optional<VariableInstantiationAttributes> mVariable;
  std::function<void(NodeSubtreeResult)> mOnComplete;

  NodeId mNewId;
  std::optional<NodeSubtree> mSubtree;
};

