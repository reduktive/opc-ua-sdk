void InstantiationService::instantiate_variable_async(const NodeId& parent, const QualifiedName& browseName,
  const NodeId& typeDefinition, const InstantiationOptions& options,
  const VariableInstantiationAttributes& attributes, InstantiateCompleteCallback complete) const noexcept
{
  try
  {
    const auto shape = validate_variable_instantiation_shape(typeDefinition, attributes);
    if (shape.is_bad())
    {
      detail::invoke_user_callback(
        std::move(complete), NodeSubtreeResult{shape.status_code(), shape.shared_detail()});
      return;
    }

    const auto limits = mAddressSpace.limits();
    const DepthBudget budget{limits.instantiationDepthLimit};

    instantiate_variable_impl_async(mAddressSpace,
      budget,
      NodeId{parent},
      QualifiedName{browseName},
      NodeId{typeDefinition},
      options,
      VariableInstantiationAttributes{attributes},
      std::move(complete));
  }
  catch (...)
  {
    detail::invoke_user_callback(
      std::move(complete), NodeSubtreeResult{ua::exception_to_status_code(std::current_exception())});
  }
}

void InstantiationService::instantiate_optional_members_async(const NodeId& instance,
  const NodeId& typeDefinition, const InstantiationOptions& options,
  std::function<void(VoidResult)> complete) const noexcept
{
  // API-D4.2: with no filter nothing would be added, so an unset filter is a caller mistake, not a no-op.
  if (!options.optionalChildFilter)
  {
    complete(VoidResult{Status::BadInvalidArgument,
      ErrorDetail::build("OptionalMembersFilterUnset",
        "no optional members were selected: options.optionalChildFilter is unset",
        "address_space.instantiation.optional_members")
        .context(ContextKeys::nodeId, instance)});
    return;
  }
  const auto limits = mAddressSpace.limits();
  const DepthBudget budget{limits.instantiationDepthLimit};

  // The apply step records every created node in a NodeSubtree whose destructor would otherwise roll the
  // nodes back. Here the materialised members are permanent additions to an existing instance, so own the
  // subtree on the heap (rooted at the instance) and release() it on completion to keep the created members
  // alive.
  auto subtree = std::make_shared<NodeSubtree>(mAddressSpace, NodeId{instance}, std::vector<NodeId>{});
  auto context = std::make_shared<instantiation_detail::InstantiationContext>();
  context->memberTypeResolver = options.memberTypeResolver;

  plan_children_async(mAddressSpace,
    budget,
    NodeId{typeDefinition},
    NodeId{instance},
    options.nodeIdAllocator,
    options.targetNamespaceIndex,
    options.optionalChildFilter,
    options.instantiateNestedTypeOptionals,
    context,
    [handle = mAddressSpace.weak(), budget, context, subtree, complete = std::move(complete)](
      VoidResult planned) mutable
    {
      if (planned.is_bad())
      {
        complete(std::move(planned));
        return;
      }
      auto locked = handle.lock();
      if (!locked)
      {
        complete(VoidResult{instantiation_address_space_gone()});
        return;
      }
      apply_plan_async(*locked,
        budget,
        std::move(context),
        subtree.get(),
        [subtree, complete = std::move(complete)](VoidResult result) mutable
        {
          // Keep the created members; only roll back on failure (best-effort).
          if (result.is_good())
          {
            subtree->release();
          }
          complete(std::move(result));
        });
    });
}

